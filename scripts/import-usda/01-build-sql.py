"""Builds supabase/usda_foods_part{1,2,3}of3.sql from the USDA FoodData Central
"SR Legacy" CSV download (public domain; https://fdc.nal.usda.gov/download-datasets).

SR Legacy has ~7,800 generic foods, each with 60+ lab-analysed nutrients, which
is what the app borrows from when a logged food (a photo scan, a custom food,
many barcodes) came without vitamins and minerals and AUSNUT has no close match.

Usage (the extracted folder holds food.csv, food_nutrient.csv, ...):
  python3 -I scripts/import-usda/01-build-sql.py <extracted-folder> supabase

Per 100 g, in the units ausnut_foods uses. A nutrient the source has no figure
for becomes NULL for the extended set and 0 for the original set (the app reads
0 there as "no data" — see src/lib/microEstimate.js hasData).
"""
import csv
import sys
from pathlib import Path

src, out = Path(sys.argv[1]), Path(sys.argv[2])

# column -> (FDC nutrient ids tried in order, scale, extended?)
COLUMNS = {
    'calories': ([1008], 1, False),
    'protein_g': ([1003], 1, False),
    'carbs_g': ([1005], 1, False),
    'fat_g': ([1004], 1, False),
    'fibre_g': ([1079], 1, False),
    'sodium_mg': ([1093], 1, False),
    'sugar_g': ([2000, 1063], 1, False),
    'saturated_fat_g': ([1258], 1, False),
    'trans_fat_g': ([1257], 1, False),
    'cholesterol_mg': ([1253], 1, False),
    'potassium_mg': ([1092], 1, False),
    'vitamin_d_mcg': ([1114], 1, False),
    'calcium_mg': ([1087], 1, False),
    'iron_mg': ([1089], 1, False),
    'vitamin_a_mcg': ([1106], 1, False),
    'vitamin_c_mg': ([1162], 1, False),
    'vitamin_b12_mcg': ([1178], 1, False),
    'folate_mcg': ([1190, 1177], 1, False),
    'magnesium_mg': ([1090], 1, False),
    'zinc_mg': ([1095], 1, False),
    'polyunsaturated_fat_g': ([1293], 1, False),
    'monounsaturated_fat_g': ([1292], 1, False),
    'thiamin_mg': ([1165], 1, True),
    'riboflavin_mg': ([1166], 1, True),
    'niacin_mg': ([1167], 1, True),
    'vitamin_b6_mg': ([1175], 1, True),
    'vitamin_e_mg': ([1109], 1, True),
    'phosphorus_mg': ([1091], 1, True),
    'selenium_mcg': ([1103], 1, True),
    'iodine_mcg': ([1100], 1, True),
    'vitamin_k_mcg': ([1185], 1, True),
    'choline_mg': ([1180], 1, True),
    'copper_mg': ([1098], 1, True),
    'manganese_mg': ([1101], 1, True),
    'omega6_g': ([1316], 1, True),
    'ala_g': ([1404], 1, True),
    'caffeine_mg': ([1057], 1, True),
    'alcohol_g': ([1018], 1, True),
}
# Long-chain omega-3 = EPA + DPA + DHA, grams -> milligrams.
OMEGA3_IDS = [1278, 1280, 1272]

wanted = {i for ids, _, _ in COLUMNS.values() for i in ids} | set(OMEGA3_IDS)
foods = {}
for r in csv.DictReader(open(src / 'food.csv', encoding='utf-8')):
    foods[r['fdc_id']] = {'name': r['description'].strip(), 'n': {}}
for r in csv.DictReader(open(src / 'food_nutrient.csv', encoding='utf-8')):
    nid = int(r['nutrient_id'])
    if nid in wanted and r['fdc_id'] in foods and r['amount'] != '':
        foods[r['fdc_id']]['n'][nid] = float(r['amount'])

cols = list(COLUMNS) + ['omega3_mg']


def q(s):
    return "'" + s.replace("'", "''") + "'"


def num(v):
    return 'null' if v is None else repr(round(v, 4)).rstrip('0').rstrip('.') if '.' in repr(round(v, 4)) else repr(round(v, 4))


rows = []
for fdc_id, f in sorted(foods.items(), key=lambda kv: int(kv[0])):
    n = f['n']
    if 1008 not in n:
        continue
    vals = []
    for col, (ids, scale, ext) in COLUMNS.items():
        v = next((n[i] * scale for i in ids if i in n), None)
        vals.append(num(v if v is not None else (None if ext else 0)))
    parts = [n[i] for i in OMEGA3_IDS if i in n]
    vals.append(num(sum(parts) * 1000 if parts else None))
    rows.append(f"({q('usda-' + fdc_id)}, {q(f['name'])}, 'USDA SR Legacy', " + ', '.join(vals) + ')')

header = ', '.join(['id', 'name', 'derivation'] + cols)
update = ', '.join(f'{c} = excluded.{c}' for c in ['name', 'derivation'] + cols)
n_parts = 3
size = -(-len(rows) // n_parts)
for p in range(n_parts):
    chunk = rows[p * size:(p + 1) * size]
    (out / f'usda_foods_part{p + 1}of{n_parts}.sql').write_text(
        f"-- USDA reference foods, part {p + 1} of {n_parts} ({len(chunk)} foods, per 100 g).\n"
        "-- Loads public.usda_foods — run the \"USDA reference foods\" block of supabase/schema.sql\n"
        "-- (or pending-migrations.sql) first, then the \"More nutrients\" block. Run all 3 parts, in any order. Safe to re-run (upserts by id).\n"
        "-- Generated by scripts/import-usda/01-build-sql.py from the USDA FoodData Central SR Legacy\n"
        "-- download (public domain) — do not edit by hand; re-run the script instead.\n"
        "begin;\n"
        f"insert into public.usda_foods ({header}) values\n" + ',\n'.join(chunk) +
        f"\non conflict (id) do update set {update};\ncommit;\n",
        encoding='utf-8')
print(f'{len(rows)} foods -> {n_parts} files in {out}')
